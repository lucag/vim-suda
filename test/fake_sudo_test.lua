-- Contract of the fake `sudo` used by the vim-suda tests.
local h = dofile(vim.fs.dirname(arg[0]) .. '/helpers.lua')

h.test('cached credential: -n runs the command and logs its argv', function()
  local fake = h.fake_sudo({ state = 'cached' })
  local r = fake.run({ '-p', '', '-n', '--', 'echo', 'hello world' })
  h.eq(0, r.code, r.stderr)
  h.eq('hello world\n', r.stdout)
  local calls = fake.calls()
  h.eq(1, #calls)
  h.eq({ '-p', '', '-n', '--', 'echo', 'hello world' }, calls[1].argv)
end)

h.test('not cached: -n fails with a password-required error', function()
  local fake = h.fake_sudo({ state = 'uncached' })
  local r = fake.run({ '-n', '--', 'echo', 'hi' })
  h.eq(1, r.code)
  h.eq('', r.stdout)
  h.eq('sudo: a password is required\n', r.stderr)
end)

h.test('not cached: -S with the right password runs the command and caches the credential', function()
  local fake = h.fake_sudo({ state = 'uncached', password = 'secret' })
  local r = fake.run({ '-p', '', '-S', '--', 'cat' }, 'secret\npayload')
  h.eq(0, r.code, r.stderr)
  h.eq('payload', r.stdout, 'the command receives stdin after the password line')
  h.eq('secret\npayload', fake.calls()[1].stdin)
  h.eq('cached', fake.state())
  h.eq(0, fake.run({ '-n', '-v' }).code, 'later -n -v succeeds')
end)

h.test('cached: -S passes all of stdin to the command', function()
  local fake = h.fake_sudo({ state = 'cached' })
  local r = fake.run({ '-S', '--', 'cat' }, 'payload\n')
  h.eq('payload\n', r.stdout)
end)

h.test('wrong-password: -S rejects any password and runs nothing', function()
  local fake = h.fake_sudo({ state = 'wrong-password', password = 'secret' })
  local r = fake.run({ '-S', '--', 'echo', 'ran' }, 'secret\n')
  h.eq(1, r.code)
  h.eq('', r.stdout)
  h.eq('sudo: 1 incorrect password attempt\n', r.stderr)
  h.eq('wrong-password', fake.state())
end)

h.test('-v validates without running a command', function()
  h.eq(0, h.fake_sudo({ state = 'cached' }).run({ '-n', '-v' }).code)
  h.eq(1, h.fake_sudo({ state = 'uncached' }).run({ '-n', '-v' }).code)
end)

h.test('failing command: reports its stderr and exits 1', function()
  local fake = h.fake_sudo({ state = 'cached', fail = { cmd = 'cat', stderr = 'cat: disk full\n' } })
  local r = fake.run({ '-n', '--', '/bin/cat', '/etc/hostname' })
  h.eq(1, r.code)
  h.eq('', r.stdout)
  h.eq('cat: disk full\n', r.stderr)
  h.eq(0, fake.run({ '-n', '--', 'true' }).code, 'other commands still run')
end)

h.test('logs the session id and terminal number of the fake process', function()
  local fake = h.fake_sudo({ state = 'cached' })
  local nvim = vim.split(h.read_bytes('/proc/self/stat'):gsub('^.*%) ', ''), ' ')
  local nvim_sid, nvim_tty = tonumber(nvim[4]), tonumber(nvim[5])

  vim.system({ 'sudo', '-n', '--', 'true' }):wait()
  vim.system({ 'sudo', '-n', '--', 'true' }, { detach = true }):wait()
  local attached, detached = unpack(fake.calls())

  h.eq(nvim_sid, attached.sid, "an attached child shares the nvim process's session")
  h.eq(nvim_tty, attached.tty, "an attached child shares the nvim process's terminal (0 on CI)")
  h.ok(detached.sid ~= nvim_sid, 'a detached child gets a new session')
  h.eq(0, detached.tty, 'a detached child has no controlling terminal')
end)

h.test('emulates privilege on Protected Files only while the command runs', function()
  local dir = h.tempdir()
  local path = h.protected_file(dir, 'secret.txt', 'top secret\n')
  local fake = h.fake_sudo({ state = 'cached', protected = { path } })
  h.eq(0, vim.fn.filereadable(path), 'not readable before')
  local r = fake.run({ '-n', '--', 'cat', path })
  h.eq(0, r.code, r.stderr)
  h.eq('top secret\n', r.stdout)
  h.eq(0, vim.fn.filereadable(path), 'not readable after')
  h.eq('---------', vim.fn.getfperm(path), 'permissions restored')
end)

h.run()
